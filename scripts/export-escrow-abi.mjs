import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const artifact = JSON.parse(readFileSync(resolve("contracts/out/PactoraEscrow.sol/PactoraEscrow.json"), "utf8"));
if (!Array.isArray(artifact.abi) || !artifact.abi.some((entry) => entry.name === "VERSION")) throw new Error("Build Pactora V2 before generating its ABI.");
writeFileSync(resolve("lib/chain/abi/PactoraEscrow.ts"), `// Generated by pnpm contracts:abi from the tested Foundry artifact.\nexport const PACTORA_ESCROW_ABI = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`);
console.log("Exported Pactora V2 ABI from the compiled artifact.");
